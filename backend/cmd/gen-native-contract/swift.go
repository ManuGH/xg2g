// Swift keywords that cannot appear bare as a declaration name. Wire names are
// lowerCamelCase already, so this is a guard against a future spec field named
// `default` or `protocol` rather than a transformation applied today.
var swiftKeywords = map[string]bool{
	"associatedtype": true, "as": true, "break": true, "case": true, "catch": true,
	"class": true, "continue": true, "default": true, "defer": true, "deinit": true,
	"do": true, "else": true, "enum": true, "extension": true, "fallthrough": true,
	"false": true, "fileprivate": true, "for": true, "func": true, "guard": true,
	"if": true, "import": true, "in": true, "init": true, "inout": true,
	"internal": true, "is": true, "let": true, "nil": true, "operator": true,
	"private": true, "protocol": true, "public": true, "repeat": true, "rethrows": true,
	"return": true, "self": true, "static": true, "struct": true, "subscript": true,
	"super": true, "switch": true, "throw": true, "throws": true, "true": true,
	"try": true, "typealias": true, "var": true, "where": true, "while": true,
}

func renderSwift(model *contract) []byte {
	var out bytes.Buffer

	out.WriteString("// Code generated by gen-native-contract from backend/api/openapi.yaml; DO NOT EDIT.\n")
	out.WriteString("//\n")
	out.WriteString("// Copyright (c) 2026 ManuGH\n")
	out.WriteString("// Licensed under the PolyForm Noncommercial License 1.0.0\n")
	out.WriteString("// Since v2.0.0, this software is restricted to non-commercial use only.\n\n")
	out.WriteString("import Foundation\n\n")
	out.WriteString("/// The wire contract, as published by the server rather than as remembered by\n")
	out.WriteString("/// the client.\n")
	out.WriteString("///\n")
	out.WriteString("/// A caseless enum rather than a module: the app is a single target, and\n")
	out.WriteString("/// namespacing keeps these names from colliding with the domain types that\n")
	out.WriteString("/// wrap them.\n")
	out.WriteString("///\n")
	out.WriteString("/// `Date` fields are RFC 3339 on the wire. Decode with `JSONDecoder.xg2g`,\n")
	out.WriteString("/// which accepts Go's fractional and non-fractional forms; Foundation's\n")
	out.WriteString("/// `.iso8601` strategy rejects the fractional one.\n")
	out.WriteString("enum Xg2gContract {\n")

	for _, model := range model.enums {
		writeSwiftEnum(&out, model)
	}
	for _, model := range model.objects {
		writeSwiftObject(&out, model)
	}

	out.WriteString("}\n")
	return out.Bytes()
}

func writeSwiftEnum(out *bytes.Buffer, model enumModel) {
	writeSwiftDoc(out, "    ", model.doc)
	fmt.Fprintf(out, "    enum %s: String, Codable, Sendable, CaseIterable, Equatable {\n", model.name)
	for _, value := range model.values {
		name := swiftEnumCase(value)
		if name == value {
			fmt.Fprintf(out, "        case %s\n", name)
			continue
		}
		fmt.Fprintf(out, "        case %s = %q\n", name, value)
	}
	out.WriteString("    }\n\n")
}

func writeSwiftObject(out *bytes.Buffer, model objectModel) {
	writeSwiftDoc(out, "    ", model.doc)
	fmt.Fprintf(out, "    struct %s: Codable, Sendable, Equatable {\n", model.name)

	for _, f := range model.fields {
		writeSwiftDoc(out, "        ", f.doc)
		optional := ""
		if !f.required {
			optional = "?"
		}
		fmt.Fprintf(out, "        let %s: %s%s\n", swiftIdentifier(f.wire), swiftType(f.typ), optional)
	}

	writeSwiftCodingKeys(out, model)

	// A memberwise initialiser is synthesised as `internal`, which is enough for
	// a single-target app but not for tests that build the type explicitly, so
	// it is emitted rather than relied upon.
	// Required parameters first, defaulted ones after, so a caller can construct
	// the type by naming only what the contract actually demands. Fields
	// themselves stay in spec order; only the initialiser is regrouped.
	params := make([]field, 0, len(model.fields))
	for _, f := range model.fields {
		if f.required {
			params = append(params, f)
		}
	}
	for _, f := range model.fields {
		if !f.required {
			params = append(params, f)
		}
	}

	out.WriteString("\n        init(\n")
	for i, f := range params {
		optional := ""
		def := ""
		if !f.required {
			optional = "?"
			def = " = nil"
		}
		comma := ","
		if i == len(params)-1 {
			comma = ""
		}
		fmt.Fprintf(out, "            %s: %s%s%s%s\n", swiftIdentifier(f.wire), swiftType(f.typ), optional, def, comma)
	}
	out.WriteString("        ) {\n")
	for _, f := range model.fields {
		name := swiftIdentifier(f.wire)
		fmt.Fprintf(out, "            self.%s = %s\n", name, name)
	}
	out.WriteString("        }\n")
	out.WriteString("    }\n\n")
}

// writeSwiftCodingKeys emits the wire mapping only when a property name and its
// JSON key differ. Synthesised keys are correct for the camelCase majority, and
// emitting them anyway would bury the handful of fields that really are spelled
// differently on the wire.
func writeSwiftCodingKeys(out *bytes.Buffer, model objectModel) {
	needed := false
	for _, f := range model.fields {
		if swiftIdentifier(f.wire) != f.wire {
			needed = true
			break
		}
	}
	if !needed {
		return
	}

	out.WriteString("\n        private enum CodingKeys: String, CodingKey {\n")
	for _, f := range model.fields {
		name := swiftIdentifier(f.wire)
		if name == f.wire {
			fmt.Fprintf(out, "            case %s\n", name)
			continue
		}
		fmt.Fprintf(out, "            case %s = %q\n", name, f.wire)
	}
	out.WriteString("        }\n")
}

func writeSwiftDoc(out *bytes.Buffer, indent, doc string) {
	for _, line := range docLines(doc) {
		if line == "" {
			fmt.Fprintf(out, "%s///\n", indent)
			continue
		}
		fmt.Fprintf(out, "%s/// %s\n", indent, line)
	}
}

func swiftType(t fieldType) string {
	switch t.kind {
	case kindString:
		return "String"
	case kindInt32:
		return "Int"
	case kindInt64:
		return "Int64"
	case kindDouble:
		return "Double"
	case kindBool:
		return "Bool"
	case kindDateTime:
		return "Date"
	case kindNamedEnum, kindNamedObject:
		return t.name
	case kindArray:
		return "[" + swiftType(*t.elem) + "]"
	case kindMap:
		return "[String: " + swiftType(*t.elem) + "]"
	default:
		panic(fmt.Sprintf("unhandled field kind %d", t.kind))
	}
}

// swiftIdentifier renders a wire name as an idiomatic Swift property name.
// The wire spelling is not thrown away — writeSwiftObject emits CodingKeys
// whenever the two differ, so the mapping stays explicit and checkable.
func swiftIdentifier(wire string) string {
	name := lowerCamelCase(wire)
	if swiftKeywords[name] {
		return "`" + name + "`"
	}
	return name
}

// swiftEnumCase turns a wire value into a lowerCamelCase case name: `local_https`
// becomes `localHttps`, `P-256` becomes `p256`.
func swiftEnumCase(value string) string {
	name := lowerCamelCase(value)
	if name == "" {
		return "unknown"
	}
	if swiftKeywords[name] {
		return "`" + name + "`"
	}
	return name
}
