// Kotlin hard keywords. Wire names are lowerCamelCase, so as with Swift this
// guards a future spec field rather than transforming anything today.
var kotlinKeywords = map[string]bool{
	"as": true, "break": true, "class": true, "continue": true, "do": true,
	"else": true, "false": true, "for": true, "fun": true, "if": true,
	"in": true, "interface": true, "is": true, "null": true, "object": true,
	"package": true, "return": true, "super": true, "this": true, "throw": true,
	"true": true, "try": true, "typealias": true, "typeof": true, "val": true,
	"var": true, "when": true, "while": true,
}

const kotlinPackage = "io.github.manugh.xg2g.android.contract"

func renderKotlin(model *contract) []byte {
	var out bytes.Buffer

	out.WriteString("// Code generated by gen-native-contract from backend/api/openapi.yaml; DO NOT EDIT.\n")
	out.WriteString("//\n")
	out.WriteString("// Copyright (c) 2026 ManuGH\n")
	out.WriteString("// Licensed under the PolyForm Noncommercial License 1.0.0\n")
	out.WriteString("// Since v2.0.0, this software is restricted to non-commercial use only.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", kotlinPackage)
	out.WriteString("import java.time.Instant\n")
	out.WriteString("import org.json.JSONArray\n")
	out.WriteString("import org.json.JSONObject\n\n")

	out.WriteString("/**\n")
	out.WriteString(" * Raised when a response does not match the published contract.\n")
	out.WriteString(" *\n")
	out.WriteString(" * A missing required field is a contract violation, not a value to paper over\n")
	out.WriteString(" * with a default. Reporting which field failed is what turns a silent decode\n")
	out.WriteString(" * into a diagnosable one.\n")
	out.WriteString(" */\n")
	out.WriteString("class Xg2gContractException(message: String) : RuntimeException(message)\n\n")

	writeKotlinPrimitives(&out)

	for _, model := range model.enums {
		writeKotlinEnum(&out, model)
	}
	for _, model := range model.objects {
		writeKotlinObject(&out, model)
	}

	return out.Bytes()
}

// writeKotlinPrimitives emits the strict field readers the generated decoders
// share. org.json is lenient by design — optString returns "" for a missing key
// and coerces neighbouring types — which is exactly the behaviour that let the
// hand-written clients drift without ever failing loudly.
func writeKotlinPrimitives(out *bytes.Buffer) {
	out.WriteString(`private fun JSONObject.requireField(name: String, owner: String): Any {
    if (isNull(name)) {
        throw Xg2gContractException("$owner: missing required field '$name'")
    }
    return get(name)
}

private fun requireString(value: Any, owner: String, name: String): String =
    value as? String ?: throw Xg2gContractException("$owner: field '$name' is not a string")

private fun requireInt(value: Any, owner: String, name: String): Int =
    (value as? Number)?.toInt() ?: throw Xg2gContractException("$owner: field '$name' is not a number")

private fun requireLong(value: Any, owner: String, name: String): Long =
    (value as? Number)?.toLong() ?: throw Xg2gContractException("$owner: field '$name' is not a number")

private fun requireDouble(value: Any, owner: String, name: String): Double =
    (value as? Number)?.toDouble() ?: throw Xg2gContractException("$owner: field '$name' is not a number")

private fun requireBoolean(value: Any, owner: String, name: String): Boolean =
    value as? Boolean ?: throw Xg2gContractException("$owner: field '$name' is not a boolean")

private fun requireObject(value: Any, owner: String, name: String): JSONObject =
    value as? JSONObject ?: throw Xg2gContractException("$owner: field '$name' is not an object")

private fun requireArray(value: Any, owner: String, name: String): JSONArray =
    value as? JSONArray ?: throw Xg2gContractException("$owner: field '$name' is not an array")

// RFC 3339, matching ` + "`format: date-time`" + ` in the spec. Instant.parse accepts both
// the fractional and non-fractional forms Go's time.Time emits.
private fun requireInstant(value: Any, owner: String, name: String): Instant {
    val text = requireString(value, owner, name)
    return runCatching { Instant.parse(text) }.getOrElse {
        throw Xg2gContractException("$owner: field '$name' is not an RFC 3339 timestamp: $text")
    }
}

private fun JSONObject.optionalField(name: String): Any? = if (isNull(name)) null else get(name)

`)
}

func writeKotlinEnum(out *bytes.Buffer, model enumModel) {
	writeKotlinDoc(out, "", model.doc)
	fmt.Fprintf(out, "enum class %s(val wireValue: String) {\n", model.name)
	for i, value := range model.values {
		terminator := ","
		if i == len(model.values)-1 {
			terminator = ";"
		}
		fmt.Fprintf(out, "    %s(%q)%s\n", kotlinEnumConstant(value), value, terminator)
	}
	out.WriteString("\n    companion object {\n")
	fmt.Fprintf(out, "        fun fromWire(value: String, owner: String = %q): %s =\n", model.name, model.name)
	out.WriteString("            entries.firstOrNull { it.wireValue == value }\n")
	fmt.Fprintf(out, "                ?: throw Xg2gContractException(\"$owner: '$value' is not a known %s\")\n", model.name)
	out.WriteString("    }\n")
	out.WriteString("}\n\n")
}

func writeKotlinObject(out *bytes.Buffer, model objectModel) {
	writeKotlinDoc(out, "", model.doc)
	fmt.Fprintf(out, "data class %s(\n", model.name)
	for i, f := range model.fields {
		writeKotlinDoc(out, "    ", f.doc)
		nullable := ""
		def := ""
		if !f.required {
			// Defaulted so a caller constructs the type by naming only what the
			// contract actually demands.
			nullable = "?"
			def = " = null"
		}
		comma := ","
		if i == len(model.fields)-1 {
			comma = ""
		}
		fmt.Fprintf(out, "    val %s: %s%s%s%s\n", kotlinIdentifier(f.wire), kotlinType(f.typ), nullable, def, comma)
	}
	out.WriteString(") {\n")
	out.WriteString("    companion object {\n")
	fmt.Fprintf(out, "        fun fromJson(json: JSONObject, owner: String = %q): %s = %s(\n", model.name, model.name, model.name)
	for i, f := range model.fields {
		comma := ","
		if i == len(model.fields)-1 {
			comma = ""
		}
		fmt.Fprintf(out, "            %s = %s%s\n", kotlinIdentifier(f.wire), kotlinReader(f), comma)
	}
	out.WriteString("        )\n")
	out.WriteString("    }\n\n")

	// The request types travel in the other direction, and a hand-built
	// JSONObject on the way out is the same drift risk as a hand-parsed one on
	// the way in. Emitting both directions keeps the contract symmetric.
	out.WriteString("    fun toJson(): JSONObject = JSONObject().apply {\n")
	for _, f := range model.fields {
		fmt.Fprintf(out, "        %s\n", kotlinWriter(f))
	}
	out.WriteString("    }\n")
	out.WriteString("}\n\n")
}

// kotlinWriter renders the statement that writes one field into a JSONObject.
// An absent optional is omitted rather than written as JSON null: the spec
// distinguishes the two, and org.json's put(name, null) removes the key anyway.
func kotlinWriter(f field) string {
	if f.required {
		return fmt.Sprintf("put(%q, %s)", f.wire, kotlinEncode(f.typ, kotlinIdentifier(f.wire)))
	}
	return fmt.Sprintf("%s?.let { put(%q, %s) }", kotlinIdentifier(f.wire), f.wire, kotlinEncode(f.typ, "it"))
}

func kotlinEncode(t fieldType, expr string) string {
	switch t.kind {
	case kindString, kindInt32, kindInt64, kindDouble, kindBool:
		return expr
	case kindDateTime:
		return expr + ".toString()"
	case kindNamedEnum:
		return expr + ".wireValue"
	case kindNamedObject:
		return expr + ".toJson()"
	case kindArray:
		return fmt.Sprintf("JSONArray(%s.map { element -> %s })", expr, kotlinEncode(*t.elem, "element"))
	case kindMap:
		return fmt.Sprintf("JSONObject(%s.mapValues { (_, value) -> %s })", expr, kotlinEncode(*t.elem, "value"))
	default:
		panic(fmt.Sprintf("unhandled field kind %d", t.kind))
	}
}

// kotlinReader renders the expression that reads one field out of a JSONObject.
// Required fields go through requireField, which throws on absence; optional
// fields resolve to null so a caller cannot mistake "absent" for a zero value.
func kotlinReader(f field) string {
	name := fmt.Sprintf("%q", f.wire)
	if f.required {
		return kotlinConvert(f.typ, fmt.Sprintf("json.requireField(%s, owner)", name), name)
	}
	return fmt.Sprintf("json.optionalField(%s)?.let { %s }", name, kotlinConvert(f.typ, "it", name))
}

func kotlinConvert(t fieldType, expr, name string) string {
	switch t.kind {
	case kindString:
		return fmt.Sprintf("requireString(%s, owner, %s)", expr, name)
	case kindInt32:
		return fmt.Sprintf("requireInt(%s, owner, %s)", expr, name)
	case kindInt64:
		return fmt.Sprintf("requireLong(%s, owner, %s)", expr, name)
	case kindDouble:
		return fmt.Sprintf("requireDouble(%s, owner, %s)", expr, name)
	case kindBool:
		return fmt.Sprintf("requireBoolean(%s, owner, %s)", expr, name)
	case kindDateTime:
		return fmt.Sprintf("requireInstant(%s, owner, %s)", expr, name)
	case kindNamedEnum:
		return fmt.Sprintf("%s.fromWire(requireString(%s, owner, %s), owner)", t.name, expr, name)
	case kindNamedObject:
		return fmt.Sprintf("%s.fromJson(requireObject(%s, owner, %s), owner)", t.name, expr, name)
	case kindArray:
		element := kotlinConvert(*t.elem, "array.get(index)", name)
		return fmt.Sprintf(
			"requireArray(%s, owner, %s).let { array -> (0 until array.length()).map { index -> %s } }",
			expr, name, element)
	case kindMap:
		element := kotlinConvert(*t.elem, "obj.get(key)", name)
		return fmt.Sprintf(
			"requireObject(%s, owner, %s).let { obj -> obj.keys().asSequence().associateWith { key -> %s } }",
			expr, name, element)
	default:
		panic(fmt.Sprintf("unhandled field kind %d", t.kind))
	}
}

func kotlinType(t fieldType) string {
	switch t.kind {
	case kindString:
		return "String"
	case kindInt32:
		return "Int"
	case kindInt64:
		return "Long"
	case kindDouble:
		return "Double"
	case kindBool:
		return "Boolean"
	case kindDateTime:
		return "Instant"
	case kindNamedEnum, kindNamedObject:
		return t.name
	case kindArray:
		return "List<" + kotlinType(*t.elem) + ">"
	case kindMap:
		return "Map<String, " + kotlinType(*t.elem) + ">"
	default:
		panic(fmt.Sprintf("unhandled field kind %d", t.kind))
	}
}

func writeKotlinDoc(out *bytes.Buffer, indent, doc string) {
	lines := docLines(doc)
	if len(lines) == 0 {
		return
	}
	fmt.Fprintf(out, "%s/**\n", indent)
	for _, line := range lines {
		if line == "" {
			fmt.Fprintf(out, "%s *\n", indent)
			continue
		}
		fmt.Fprintf(out, "%s * %s\n", indent, line)
	}
	fmt.Fprintf(out, "%s */\n", indent)
}

// kotlinIdentifier renders a wire name as an idiomatic Kotlin property name.
// The wire spelling survives in the generated fromJson/toJson bodies, which
// address every field by its literal JSON key.
func kotlinIdentifier(wire string) string {
	name := lowerCamelCase(wire)
	if kotlinKeywords[name] {
		return "`" + name + "`"
	}
	return name
}

// kotlinEnumConstant turns a wire value into an UPPER_SNAKE_CASE constant:
// `local_https` becomes `LOCAL_HTTPS`, `P-256` becomes `P_256`.
func kotlinEnumConstant(value string) string {
	parts := splitWireWords(value)
	if len(parts) == 0 {
		return "UNKNOWN"
	}
	upper := make([]string, 0, len(parts))
	for _, part := range parts {
		upper = append(upper, strings.ToUpper(part))
	}
	name := strings.Join(upper, "_")
	if unicode.IsDigit(rune(name[0])) {
		return "_" + name
	}
	return name
}
